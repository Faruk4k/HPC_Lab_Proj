def sanitize(name):
    return (
        str(name)
        .replace("stage1:", "")
        .replace("stage2:", "")
        .replace(" ", "")
        .replace("-", "_")
        .replace("+", "p")
        .replace(".", "p")
    )


df = pd.read_csv(INPUT)

required = ["benchmark", "pf_level", "memory", "config", "speedup_vs_imp_default"]
missing = [c for c in required if c not in df.columns]
if missing:
    raise RuntimeError(f"Missing columns in {INPUT}: {missing}")

stage3_configs = {}
plan = {}

for (benchmark, pf_level, memory), sub in df.groupby(["benchmark", "pf_level", "memory"]):
    sub = sub.copy()

    # Remove default; Stage 3 is about extending tuned configs.
    sub = sub[sub["config"] != "default"]

    top = (
        sub.sort_values("speedup_vs_imp_default", ascending=False)
        .drop_duplicates(subset=["config"])
        .head(TOP_N)
    )

    case_key = f"{benchmark}|{pf_level}|{memory}"
    plan[case_key] = []

    for _, row in top.iterrows():
        base_name = row["config"]

        if base_name not in imp_stage2_configurations:
            print(f"WARNING: {base_name} not found in imp_stage2_configurations, skipping")
            continue

        base_params = dict(imp_stage2_configurations[base_name])

        for dist in DISTANCES:
            new_params = dict(base_params)
            new_params["streaming_distance"] = dist

            new_name = f"{sanitize(base_name)}_s{dist}"

            # If two cases generate the same config name with same params, reuse it.
            if new_name in stage3_configs and stage3_configs[new_name] != new_params:
                raise RuntimeError(f"Name collision for {new_name}")

            stage3_configs[new_name] = new_params
            plan[case_key].append(new_name)

# Remove duplicates within each case.
for k in plan:
    plan[k] = sorted(set(plan[k]))

Path(PLAN_OUT).write_text(json.dumps(plan, indent=2, sort_keys=True))

