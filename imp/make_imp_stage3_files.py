def load_stage2_configs(path="imp_stage2_configs.py"):
    text = Path(path).read_text()
    tree = ast.parse(text)

    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if getattr(target, "id", None) == "imp_stage2_configurations":
                    return ast.literal_eval(node.value)

    raise RuntimeError("Could not find imp_stage2_configurations")

imp_stage2_configurations = load_stage2_configs()

